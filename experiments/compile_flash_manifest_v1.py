#!/usr/bin/env python3
import json, sys
from pathlib import Path

VALID = {"promoted", "candidate_reverify", "rejected", "rejected_family"}

def rust_bool(x): return "true" if x else "false"

def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: compile_flash_manifest_v1.py manifest.json output.rs")
    src, out = map(Path, sys.argv[1:])
    doc = json.loads(src.read_text())
    assert doc["schema"] == "mathgraph.flash.capabilities.v1"
    caps = doc["capabilities"]
    ids = {c["id"] for c in caps}
    assert len(ids) == len(caps)
    for c in caps:
        assert c["status"] in VALID
        for d in c.get("dependencies", []):
            assert d in ids
    # Runtime sees only promoted capabilities. Candidate evidence never mutates
    # executable policy until an external authority changes status to promoted.
    promoted = {c["id"] for c in caps if c["status"] == "promoted"}
    lines = [
        "// @generated by experiments/compile_flash_manifest_v1.py",
        "// Do not edit by hand. Runtime policy contains promoted capabilities only.",
        "",
        f"pub(crate) const DIRECT_VAR_EVAL: bool = {rust_bool('direct_var_eval' in promoted)};",
        f"pub(crate) const DIRECT_FRAMED_PRUNE: bool = {rust_bool('direct_framed_prune' in promoted)};",
        "",
        "pub(crate) const PROMOTED_CAPABILITY_IDS: &[&str] = &[",
    ]
    for cid in sorted(promoted):
        lines.append(f'    "{cid}",')
    lines += ["];", ""]
    out.write_text("\n".join(lines))
    print("FLASH_MANIFEST_COMPILED", ",".join(sorted(promoted)))

if __name__ == "__main__":
    main()
